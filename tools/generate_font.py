def get_glyphs_pillow() -> list[bytes] | None:
    """Try to extract glyphs via Pillow from a system monospace font."""
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        return None

    # Try common monospace font paths
    font_candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf",
        "/usr/share/fonts/truetype/terminus/TerminusTTF-4.49.1.ttf",
        "C:\\Windows\\Fonts\\consola.ttf",
        "/System/Library/Fonts/Menlo.ttc",
    ]

    font = None
    for path in font_candidates:
        if os.path.exists(path):
            try:
                font = ImageFont.truetype(path, FONT_HEIGHT)
                break
            except Exception:
                continue

    if font is None:
        return None

    glyphs = []
    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        ch = chr(code)
        img = Image.new("1", (FONT_WIDTH, FONT_HEIGHT), 0)
        draw = ImageDraw.Draw(img)
        draw.text((0, 0), ch, fill=1, font=font)
        rows = []
        for y in range(FONT_HEIGHT):
            byte = 0
            for x in range(FONT_WIDTH):
                if img.getpixel((x, y)):
                    byte |= 0x80 >> x
            rows.append(byte)
        glyphs.append(bytes(rows))
    return glyphs


def emit_c(glyphs: list[bytes], out) -> None:
    out.write(
        "/* Auto-generated bitmap font — 8\xc3\x9716 pixels, ASCII 32-126 (95 glyphs).\n"
        " * Each glyph = 16 bytes.  Byte N is pixel row N (row 0 = top).\n"
        " * Bit 7 (MSB) = leftmost pixel; 1 = ink, 0 = paper.\n"
        " * Stored in .rodata (ROM) \xe2\x80\x94 zero RAM cost.\n"
        " *\n"
        " * Regenerate with:  python3 tools/generate_font.py > EPD/font8x16.c\n"
        " */\n"
        "#include \"font8x16.h\"\n"
        "\n"
        "const uint8_t font8x16[95 * 16] = {\n"
    )
    for idx, glyph in enumerate(glyphs):
        code = idx + FIRST_CHAR
        try:
            label = repr(chr(code))
        except Exception:
            label = hex(code)
        lo = ", ".join(f"0x{b:02X}" for b in glyph[:8])
        hi = ", ".join(f"0x{b:02X}" for b in glyph[8:])
        out.write(f"    /* {label} ({code}) */\n")
        out.write(f"    {lo},\n")
        out.write(f"    {hi},\n")
    out.write("};\n")


def main():
    use_stdout = "--stdout" in sys.argv

    glyphs = get_glyphs_pillow() or BUILTIN_GLYPHS

    if use_stdout:
        import sys
        buf = io.StringIO()
        emit_c(glyphs, buf)
        sys.stdout.write(buf.getvalue())
    else:
        script_dir = os.path.dirname(os.path.abspath(__file__))
        out_path = os.path.join(script_dir, "..", "EPD", "font8x16.c")
        with open(out_path, "w", encoding="utf-8") as f:
            emit_c(glyphs, f)
        print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
